#!/usr/bin/env python3
"""Regenerate cycles_6800.h from MAME's 6800 cycle table.

The table is functional technical data (how many clocks each opcode takes on
real silicon); we read it out of the local MAME tree rather than re-typing it so
it can be re-checked against upstream.

    ./extract_cycles.py [path/to/mame/src/devices/cpu/m6800/m6800.cpp]
"""
import re, sys

path = sys.argv[1] if len(sys.argv) > 1 else \
    "../../mame/src/devices/cpu/m6800/m6800.cpp"
src = open(path).read()
i = src.index("const u8 m6800_cpu_device::cycles_6800[256]")
body = src[i:src.index("};", i)]
body = body[body.index("{"):]
body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)      # drop the column-header comments
nums = re.findall(r"\b(XX|\d+)\b", body)
vals = [(-1 if n == "XX" else int(n)) for n in nums]
if len(vals) != 256:
    sys.exit(f"expected 256 entries, parsed {len(vals)}")

with open("cycles_6800.h", "w") as f:
    f.write("// Per-opcode cycle counts for the Motorola 6800.\n"
            "// GENERATED by extract_cycles.py from MAME's\n"
            "// m6800_cpu_device::cycles_6800[] -- do not edit by hand.\n"
            "// -1 marks an opcode MAME lists as illegal/unknown; the harness skips those.\n"
            "#pragma once\n\nstatic const int cycles_6800[256] = {\n")
    for r in range(16):
        f.write("\t" + ", ".join(f"{v:3}" for v in vals[r*16:(r+1)*16]) + ",\n")
    f.write("};\n")

legal = sum(1 for v in vals if v > 0)
print(f"cycles_6800.h: 256 entries, {legal} legal, {256-legal} illegal")
print("spot check: NOP(01)=%d  LDAA#(86)=%d  LDAAext(B6)=%d  JSRext(BD)=%d  SWI(3F)=%d"
      % (vals[0x01], vals[0x86], vals[0xB6], vals[0xBD], vals[0x3F]))
